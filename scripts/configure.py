#!/usr/bin/env python3
"""Generate five local dotenv files from one namespaced configuration file.

Only Python's standard library is used. Values are never evaluated or printed.
"""
import argparse
import os
from pathlib import Path
import re
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
PROJECTS = (
    ('CORE', 'core-nexus', '.env'),
    ('PC', 'kf-pc', '.env.development'),
    ('H5', 'task-distribution-app', '.env.development'),
    ('UCP', 'ucp', '.env'),
    ('INTERCEPTION', 'interception-bot', '.env'),
)
KEY = re.compile(r'^[A-Za-z_][A-Za-z_0-9]*$')


class ConfigError(Exception):
    pass


def read_env(path):
    result = {}
    for line_number, source in enumerate(path.read_text(encoding='utf-8-sig').splitlines(), 1):
        line = source.strip()
        if not line or line.startswith('#'):
            continue
        if line.startswith('export '):
            line = line[7:].lstrip()
        if '=' not in line:
            raise ConfigError('{}:{}: expected KEY=value'.format(path.name, line_number))
        name, raw = line.split('=', 1)
        name, raw = name.strip(), raw.strip()
        if not KEY.fullmatch(name):
            raise ConfigError('{}:{}: invalid key'.format(path.name, line_number))
        if name in result:
            raise ConfigError('{}:{}: duplicate key {}'.format(path.name, line_number, name))
        if raw.startswith(('"', "'")):
            if len(raw) < 2 or raw[-1] != raw[0]:
                raise ConfigError('{}:{}: use a single-line quoted value'.format(path.name, line_number))
        elif ' #' in raw:
            raw = raw.split(' #', 1)[0].rstrip()
        if '${' in raw:
            raise ConfigError('{}:{}: variable interpolation is unsupported; fill the complete value'.format(path.name, line_number))
        result[name] = raw
    return result


def value(raw):
    if len(raw) >= 2 and raw[0] in ('"', "'") and raw[-1] == raw[0]:
        return raw[1:-1]
    return raw


def plan(config_path, root):
    if not config_path.is_file():
        raise ConfigError('Copy config.example.env to config.local.env and fill your own settings first.')
    supplied = read_env(config_path)
    allowed, templates = set(), []
    for prefix, project, destination in PROJECTS:
        template = root / project / '.env.example'
        if not template.is_file():
            raise ConfigError('Missing configuration template for {}'.format(project))
        defaults = read_env(template)
        allowed.update(prefix + '__' + key for key in defaults)
        templates.append((prefix, project, destination, defaults))
    unknown = sorted(set(supplied) - allowed)
    if unknown:
        raise ConfigError('Unknown configuration key(s): ' + ', '.join(unknown))

    outputs, core = [], {}
    for prefix, project, destination, defaults in templates:
        merged = {key: supplied.get(prefix + '__' + key, raw) for key, raw in defaults.items()}
        if prefix == 'CORE':
            core = {key: value(raw) for key, raw in merged.items()}
        contents = ['# Local configuration generated by scripts/configure.py; do not commit.']
        contents.extend('{}={}'.format(key, raw) for key, raw in merged.items())
        outputs.append((root / project / destination, '\n'.join(contents) + '\n'))

    required = ('DATABASE_URL', 'REDIS_URL', 'JWT_ACCESS_SECRET', 'JWT_REFRESH_SECRET')
    missing = [key for key in required if not core.get(key)]
    if missing:
        raise ConfigError('Fill required backend keys: ' + ', '.join('CORE__' + key for key in missing))
    for key in ('JWT_ACCESS_SECRET', 'JWT_REFRESH_SECRET'):
        secret = core[key]
        if len(secret) < 32 or re.search(r'change.?me|replace.?me|your[_ -].*secret', secret, re.I):
            raise ConfigError('CORE__{} must be your own random value with at least 32 characters.'.format(key))
    if core['JWT_ACCESS_SECRET'] == core['JWT_REFRESH_SECRET']:
        raise ConfigError('Use different access and refresh JWT secrets.')
    return outputs


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=root / 'config.local.env')
    parser.add_argument('--check', action='store_true', help='validate and show output paths without writing')
    parser.add_argument('--force', action='store_true', help='replace existing local configuration files')
    args = parser.parse_args(argv)
    try:
        outputs = plan(args.config, root)
        existing = [path for path, _ in outputs if path.exists()]
        if existing and not args.force and not args.check:
            raise ConfigError('Local configuration already exists. Review it, then use --force if replacement is intended.')
        if not args.check:
            for path, contents in outputs:
                path.parent.mkdir(parents=True, exist_ok=True)
                handle, temporary = tempfile.mkstemp(prefix='.' + path.name + '.', dir=str(path.parent))
                try:
                    with os.fdopen(handle, 'w', encoding='utf-8', newline='\n') as stream:
                        stream.write(contents)
                    os.chmod(temporary, 0o600)
                    os.replace(temporary, path)
                finally:
                    if os.path.exists(temporary):
                        os.unlink(temporary)
        for path, _ in outputs:
            print(('CHECKED ' if args.check else 'WROTE ') + path.relative_to(root).as_posix())
        return 0
    except (ConfigError, OSError) as error:
        # ConfigError messages contain field names or locations, never values.
        print('Configuration error: ' + str(error), file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
