import Joi from 'joi';

export function validateEnv(config: Record<string, unknown>) {
  const schema = Joi.object({
    NODE_ENV: Joi.string().valid('development', 'test', 'production').default('development'),
    PORT: Joi.number().default(3000),
    APP_NAME: Joi.string().default('Core Nexus'),
    APP_ORIGIN: Joi.string().default('http://localhost:5173'),
    APP_BASE_URL: Joi.string().uri({ scheme: ['http', 'https'] }).optional(),
    WEBSITE_BASE_URL: Joi.string().uri({ scheme: ['http', 'https'] }).allow('').optional(),
    API_BASE_URL: Joi.string().uri({ scheme: ['http', 'https'] }).allow('').optional(),
    DATABASE_URL: Joi.string().uri({ scheme: ['postgresql', 'postgres'] }).required(),
    REDIS_URL: Joi.string().uri({ scheme: ['redis'] }).required(),
    JWT_ACCESS_SECRET: Joi.string().min(32).required(),
    JWT_REFRESH_SECRET: Joi.string().min(32).required(),
    JWT_ACCESS_EXPIRES_IN: Joi.string().default('7d'),
    JWT_REFRESH_EXPIRES_IN: Joi.string().default('7d'),
    HASH_SALT_ROUNDS: Joi.number().min(8).max(15).default(10),
    UPLOAD_DRIVER: Joi.string().valid('local', 'oss').default('local'),
    UPLOAD_MAX_FILE_SIZE_MB: Joi.number().min(1).max(100).default(20),
    LOCAL_UPLOAD_DIR: Joi.string().default('uploads'),
    OSS_REGION: Joi.string().allow('').optional(),
    OSS_BUCKET: Joi.string().allow('').optional(),
    OSS_ACCESS_KEY_ID: Joi.string().allow('').optional(),
    OSS_ACCESS_KEY_SECRET: Joi.string().allow('').optional(),
    OSS_ENDPOINT: Joi.string().allow('').optional(),
    OSS_CDN_BASE_URL: Joi.string().allow('').optional(),
    OSS_OBJECT_PREFIX: Joi.string().allow('').optional(),
    TENCENT_COS_ENABLED: Joi.string().valid('', 'true', 'false', '1', '0', 'yes', 'no', 'on', 'off', 'enabled', 'disabled').allow('').default('false'),
    TENCENT_COS_SECRET_ID: Joi.string().allow('').optional(),
    TENCENT_COS_SECRET_KEY: Joi.string().allow('').optional(),
    TENCENT_COS_REGION: Joi.string().allow('').default('ap-guangzhou'),
    TENCENT_COS_BUCKET: Joi.string().allow('').optional(),
    TENCENT_COS_PREFIX: Joi.string().allow('').default('media'),
    TENCENT_COS_SCHEME: Joi.string().valid('https', 'http').default('https'),
    TENCENT_COS_SIGNED_URL_TTL_SECONDS: Joi.number().integer().min(60).max(86400).default(600),
    TENCENT_COS_THUMBNAIL_URL_TTL_SECONDS: Joi.number().integer().min(60).max(86400).default(3600),
    TENCENT_COS_PRIVATE_SCENES: Joi.string().allow('').default(''),
    TENCENT_COS_THUMBNAIL_MAX_LONG_EDGE: Joi.number().integer().min(160).max(1024).default(320),
    TENCENT_COS_THUMBNAIL_QUALITY: Joi.number().integer().min(40).max(95).default(80),
    COZE_API_BASE_URL: Joi.string().uri({ scheme: ['http', 'https'] }).default('https://api.coze.cn'),
    COZE_API_PAT: Joi.string().allow('').optional(),
    COZE_PERSONAL_ACCESS_TOKEN: Joi.string().allow("").optional(),
    COZE_SERVICE_ACCESS_TOKEN: Joi.string().allow("").optional(),
    COZE_AUTH_MODE: Joi.string().valid("", "pat", "service_access_token", "oauth_jwt").allow("").optional(),
    COZE_OAUTH_APP_ID: Joi.string().allow("").optional(),
    COZE_OAUTH_PUBLIC_KEY_ID: Joi.string().allow("").optional(),
    COZE_OAUTH_PRIVATE_KEY: Joi.string().allow("").optional(),
    COZE_OAUTH_AUDIENCE: Joi.string().allow("").default("api.coze.cn"),
    COZE_OAUTH_DURATION_SECONDS: Joi.number().min(900).max(86399).default(3600),
    COZE_COMMENT_REPLY_WORKFLOW_ID: Joi.string().allow("").default(""),
    COZE_COMMENT_INTENT_WORKFLOW_ID: Joi.string().allow("").default(""),
    COZE_INTERCEPT_WORK_DECISION_WORKFLOW_ID: Joi.string().allow('').optional(),
    COZE_COMMENT_INTENT_BATCH_SIZE: Joi.number().min(1).max(50).default(30),
    // 同步等待模型输出的 AI 请求统一默认最多等待 10 分钟；反向代理需略大于此值。
    COZE_COMMENT_INTENT_TIMEOUT_MS: Joi.number().integer().min(30_000).max(600_000).default(600_000),
    COZE_AUTO_REPLY_TIMEOUT_MS: Joi.number().integer().min(30_000).max(600_000).default(600_000),
    DEEPSEEK_API_KEY: Joi.string().allow('').optional(),
    DEEPSEEK_BASE_URL: Joi.string().uri({ scheme: ['http', 'https'] }).allow('').optional(),
    DEEPSEEK_API_BASE_URL: Joi.string().uri({ scheme: ['http', 'https'] }).allow('').optional(),
    DEEPSEEK_MODEL: Joi.string().allow('').optional(),
    DEEPSEEK_CHAT_MODEL: Joi.string().allow('').optional(),
    DEEPSEEK_TIMEOUT_MS: Joi.number().integer().min(30_000).max(600_000).default(600_000),
    CUSTOMER_SERVICE_JSON_MAX_BYTES: Joi.number().integer().min(16_384).max(20_000_000).default(524_288),
    CUSTOMER_SERVICE_TUNING_RETENTION_DAYS: Joi.number().integer().min(30).max(3650).default(180),
    CUSTOMER_SERVICE_RAW_OUTPUT_RETENTION_DAYS: Joi.number().integer().min(7).max(3650).default(90),
    CUSTOMER_SERVICE_CALIBRATION_COMPACT_DAYS: Joi.number().integer().min(30).max(3650).default(180),
    CUSTOMER_SERVICE_GOVERNANCE_BATCH_SIZE: Joi.number().integer().min(10).max(1000).default(100),
    CUSTOMER_SERVICE_GOVERNANCE_PURGE_ENABLED: Joi.string().valid('', 'true', 'false', '1', '0', 'yes', 'no', 'on', 'off').allow('').default('false'),
    CUSTOMER_SERVICE_RUNTIME_IDEMPOTENCY_RETENTION_DAYS: Joi.number().integer().min(7).max(365).default(30),
    COZE_DM_CHAT_WORKFLOW_ID: Joi.string().allow("").default(""),
    COZE_DM_CHAT_BOT_ID: Joi.string().allow("").default(""),
    COZE_DM_CHAT_RETRY_ATTEMPTS: Joi.number().min(1).max(3).default(2),
    WECHAT_MINI_APPID: Joi.string().allow('').optional(),
    WECHAT_MINI_SECRET: Joi.string().allow('').optional(),
    WECHAT_MP_APPID: Joi.string().allow('').optional(),
    WECHAT_MP_SECRET: Joi.string().allow('').optional(),
    SMS_PROVIDER: Joi.string().valid('mock', 'tencent').default('mock'),
    SMS_ENABLED: Joi.string().valid('', 'true', 'false', '1', '0', 'yes', 'no', 'on', 'off', 'enabled', 'disabled').allow('').default('true'),
    SMS_NOTIFICATION_RESEND_INTERVAL_SECONDS: Joi.number().min(10).max(3600).default(60),
    SMS_NOTIFICATION_PHONE_DAILY_LIMIT: Joi.number().min(1).max(200).default(20),
    TENCENT_SMS_SECRET_ID: Joi.string().allow('').optional(),
    TENCENT_SMS_SECRET_KEY: Joi.string().allow('').optional(),
    TENCENT_SMS_SDK_APP_ID: Joi.string().allow('').optional(),
    TENCENT_SMS_SIGN_NAME: Joi.string().allow('').optional(),
    TENCENT_SMS_REGION: Joi.string().allow('').default('ap-guangzhou'),
    TENCENT_SMS_EXTEND_CODE: Joi.string().allow('').optional(),
    TENCENT_SMS_TEMPLATE_ACCOUNT_DISABLED_ID: Joi.string().allow('').optional(),
    APP_TRUST_PROXY_HOPS: Joi.number().integer().min(0).max(5).default(0),
    WEBSITE_CONFIG_MAX_BYTES: Joi.number().integer().min(16_384).max(1_048_576).default(262_144),
    WEBSITE_CONTACT_IP_HOURLY_LIMIT: Joi.number().integer().min(1).max(500).default(10),
    WEBSITE_CONTACT_DAILY_LIMIT: Joi.number().integer().min(1).max(100).default(5),
    WEBSITE_IP_HASH_SALT: Joi.string().min(16).allow('').optional(),
    WECHAT_OFFICIAL_APPID: Joi.string().allow('').optional(),
    WECHAT_OFFICIAL_SECRET: Joi.string().allow('').optional(),
    WECHAT_MINI_CODE_PAGE: Joi.string().allow('').default('pages/Home'),
    WECHAT_MINI_ENV_VERSION: Joi.string().valid('develop', 'trial', 'release').default('release'),
    WECHAT_SCENE_TTL_SECONDS: Joi.number().min(60).default(2592000),
    MINI_PROGRAM_FORCE_MODE: Joi.string().valid('', 'audit', 'release').allow('').optional(),
    MINI_PROGRAM_AUDIT_VERSION: Joi.string().allow('').optional(),
    MINI_PROGRAM_AUDIT_VERSIONS: Joi.string().allow('').optional(),
    MINI_PROGRAM_AUDIT_ENABLED: Joi.string().allow('').optional(),
    SEED_ADMIN_USERNAME: Joi.string().default('admin'),
    SEED_ADMIN_PASSWORD: Joi.string().min(12).allow('').optional(),
  });

  const { error, value } = schema.validate(config, {
    abortEarly: false,
    allowUnknown: true,
  });

  if (error) {
    throw new Error(`Environment validation error: ${error.message}`);
  }

  if (value.JWT_ACCESS_SECRET === value.JWT_REFRESH_SECRET) {
    throw new Error('JWT_ACCESS_SECRET 和 JWT_REFRESH_SECRET 必须填写不同的随机密钥');
  }

  return value;
}
